"""Tests for the Print Memory analysis. They need no OrcaSlicer and no printer:

    python -m unittest discover -s tests
"""
import os
import sys
import tempfile
import time
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import print_memory as pm  # noqa: E402

NOW = 1_800_000_000.0  # a fixed "now" so the tests don't depend on the clock


def job(n, status="completed", est=3600, ratio=1.1, warm=300, version="2.5.0", slicer="OrcaSlicer",
        material="PLA", filename=None, used=1.0, exists=True):
    """One Moonraker history entry. `n` counts back in hours from NOW (0 is the newest)."""
    printed = est * ratio if status == "completed" else est * ratio * used
    start = NOW - (n + 1) * 3600 * 4
    return {
        "job_id": "%06X" % n, "filename": filename or "part_%d_0.2mm_%s_1h0m.gcode" % (n, material),
        "status": status, "start_time": start, "end_time": start + printed + warm,
        "print_duration": printed, "total_duration": printed + warm,
        "filament_used": 1000.0 * used, "exists": exists,
        "metadata": {"estimated_time": est, "slicer": slicer, "slicer_version": version,
                     "filament_type": material, "filament_total": 1000.0,
                     "filament_weight_total": 3.0},
    }


def history(*jobs):
    return {"jobs": list(jobs), "server": {"klippy_state": "ready"},
            "status": {"print_stats": {"state": "standby"}}, "totals": {}, "store": []}


GCODE_HEAD = """; HEADER_BLOCK_START
; generated by OrcaSlicer 2.5.0-rc on 2026-11-01 at 10:00:00
; total layer number: 50
; HEADER_BLOCK_END
EXCLUDE_OBJECT_DEFINE NAME='Gear_v2.stl_id_0_copy_0' CENTER=100,100 POLYGON=[[0,0]]
; printing object Gear_v2.stl id:0 copy 0
G1 X10 Y10 E1
; stop printing object Gear_v2.stl id:0 copy 0
"""

GCODE_TAIL = """G1 X0 Y0
; EXECUTABLE_BLOCK_END
; CONFIG_BLOCK_START
; filament_type = PLA
; filament_settings_id = "Generic PLA @Test"
; layer_height = 0.2
; print_settings_id = 0.20mm Standard @Test
; printer_settings_id = Test printer
; sparse_infill_density = 20%
; curr_bed_type = Textured PEI Plate
; textured_plate_temp = 60
; hot_plate_temp = 70
; enable_arc_fitting = 1
; CONFIG_BLOCK_END

; total filament used [g] = 12.50
; estimated printing time (normal mode) = 1h 2m 3s
"""


class HelpersTest(unittest.TestCase):
    def test_parse_duration(self):
        self.assertEqual(pm.parse_duration("2h 43m 17s"), 2 * 3600 + 43 * 60 + 17)
        self.assertEqual(pm.parse_duration("1d 2h 3m"), 86400 + 7200 + 180)
        self.assertAlmostEqual(pm.parse_duration("0.882001s"), 0.882001)
        self.assertIsNone(pm.parse_duration("soon"))

    def test_fmt_dur(self):
        self.assertEqual(pm.fmt_dur(300), "5 min")
        self.assertEqual(pm.fmt_dur(3590), "1h 00m")
        self.assertEqual(pm.fmt_dur(3725), "1h 02m")
        self.assertEqual(pm.fmt_dur(90000), "1d 1h")

    def test_slicer_group(self):
        self.assertEqual(pm.slicer_group("OrcaSlicer", "2.5.0-alpha"), "OrcaSlicer 2.5")
        self.assertEqual(pm.slicer_group("PrusaSlicer", "2.8.1+win64"), "PrusaSlicer 2.8")
        self.assertEqual(pm.slicer_group(None, None), "Unknown slicer")

    def test_moonraker_address_parsing(self):
        m = pm.Moonraker("http://printer.local:7125/")
        self.assertEqual((m.host, m.port, m.prefix), ("printer.local", 7125, ""))
        with self.assertRaises(pm.MoonrakerError):
            pm.Moonraker("")


class GcodeTest(unittest.TestCase):
    def test_parse_gcode(self):
        info = pm.parse_gcode(GCODE_HEAD, GCODE_TAIL)
        self.assertEqual((info["slicer"], info["version"]), ("OrcaSlicer", "2.5.0-rc"))
        self.assertEqual(info["estimate"], 3723)
        self.assertEqual(info["grams"], 12.5)
        self.assertEqual(info["objects"], ["Gear_v2.stl"])
        self.assertEqual(info["material"], "PLA")
        self.assertEqual(info["printer_preset"], "Test printer")
        self.assertEqual(info["filament_preset"], "Generic PLA @Test")
        self.assertEqual(info["config"]["sparse_infill_density"], "20%")

    def test_object_names_from_exclude_object_only(self):
        head = "; generated by OrcaSlicer 2.5.0\nEXCLUDE_OBJECT_DEFINE NAME=Bracket.stl_id_3_copy_1 X\n"
        self.assertEqual(pm.parse_gcode(head, "")["objects"], ["Bracket.stl"])

    def test_read_local_gcode_head_and_tail(self):
        filler = ("G1 X1 Y1 E0.1\n" * 40000)  # pushes the tail past HEAD_BYTES
        with tempfile.TemporaryDirectory() as folder:
            path = os.path.join(folder, "plate.gcode")
            with open(path, "w", encoding="utf-8") as f:
                f.write(GCODE_HEAD + filler + GCODE_TAIL)
            info = pm.read_local_gcode(path)
        self.assertEqual(info["estimate"], 3723)
        self.assertEqual(info["objects"], ["Gear_v2.stl"])
        self.assertGreater(info["size"], pm.HEAD_BYTES)


class HistoryTest(unittest.TestCase):
    def test_time_model_per_version(self):
        jobs = ([job(i, ratio=1.1, version="2.5.0") for i in range(6)]
                + [job(10 + i, ratio=0.5, version="2.4.2") for i in range(6)])
        new = pm.time_model(jobs, "OrcaSlicer 2.5")
        old = pm.time_model(jobs, "OrcaSlicer 2.4")
        self.assertAlmostEqual(new["factor"], 1.1)
        self.assertAlmostEqual(old["factor"], 0.5)
        self.assertIsNone(pm.time_model(jobs, "OrcaSlicer 2.6"))
        self.assertEqual(pm.factor_text(new), "10% longer than Orca says")
        self.assertEqual(pm.factor_text(old, past=True), "50% shorter than Orca said")

    def test_time_model_uses_newest_window(self):
        jobs = ([job(i, ratio=1.0) for i in range(pm.TIME_WINDOW)]
                + [job(100 + i, ratio=2.0) for i in range(30)])
        self.assertAlmostEqual(pm.time_model(jobs, "OrcaSlicer 2.5")["factor"], 1.0)

    def test_short_and_odd_prints_are_ignored(self):
        jobs = [job(i, est=300) for i in range(10)] + [job(20 + i, ratio=9.0) for i in range(10)]
        self.assertEqual(pm.time_samples(jobs), [])

    def test_summary_counts_and_insights(self):
        jobs = [job(i) for i in range(10)]
        jobs += [job(20 + i, status="cancelled", used=0.02) for i in range(4)]  # early cancels
        for i in range(3):
            j = job(30 + i, status="klippy_shutdown", used=0.0)
            j["print_duration"] = 0.0
            jobs.append(j)
        out = pm.summarize_printer(history(*jobs), now=NOW)
        self.assertEqual(out["finished"], {"done": 10, "total": 17, "pct": 59})
        self.assertEqual({s["label"]: s["n"] for s in out["stops"]},
                         {"Cancelled": 4, "Klipper shut down": 3})
        texts = " ".join(i["text"] for i in out["insights"])
        self.assertIn("first 10 minutes", texts)
        self.assertIn("never got to the first layer", texts)
        self.assertEqual(len(out["recent_stops"]), 6)
        self.assertEqual(out["recent_stops"][0]["kind"], "Cancelled")

    def test_materials_and_lengths(self):
        jobs = [job(i, material="PETG") for i in range(4)] + [job(10, status="error", material="PETG")]
        out = pm.summarize_printer(history(*jobs), now=NOW)
        self.assertEqual(out["materials"], [{"name": "PETG", "done": 4, "total": 5, "pct": 80}])
        self.assertEqual(out["lengths"][0]["name"], "1 to 4 h")

    def test_interrupted_print_without_progress(self):
        j = job(0, status="interrupted")
        j["print_duration"], j["end_time"] = 0.0, None
        stop = pm.summarize_printer(history(j), now=NOW)["recent_stops"][0]
        self.assertIn("wasn't saved", stop["progress"])
        self.assertTrue(stop["when"].startswith("started "))

    def test_store_reason(self):
        store = [{"time": 1000.0, "type": "command", "message": "G28"},
                 {"time": 1040.0, "type": "response", "message": "!! Move out of range: 1 2 3"},
                 {"time": 5000.0, "type": "response", "message": "!! later, unrelated"}]
        reason = pm.store_reason(store, 1050.0)
        self.assertEqual(reason, "Move out of range: 1 2 3")
        self.assertIn("outside the printer's travel", pm.explain_reason(reason))
        self.assertIsNone(pm.store_reason(store, 3000.0))
        cancel = [{"time": 99.0, "type": "command", "message": "CANCEL_PRINT"}]
        self.assertEqual(pm.store_reason(cancel, 100.0), "CANCEL_PRINT was sent")

    def test_printing_state_and_time_left(self):
        data = history(*[job(i) for i in range(6)])
        data["status"] = {"print_stats": {"state": "printing", "print_duration": 1800},
                          "virtual_sdcard": {"progress": 0.4}}
        data["file_meta"] = {"estimated_time": 3600, "slicer": "OrcaSlicer",
                             "slicer_version": "2.5.0"}
        text, left, cls = pm.printer_state(data, {"OrcaSlicer 2.5": 1.1}, NOW)
        self.assertEqual(cls, "busy")
        self.assertAlmostEqual(left, 3600 * 1.1 - 1800)
        self.assertIn("Printing 40%", text)


class ModelTest(unittest.TestCase):
    def test_same_model_needs_a_name_boundary(self):
        jobs = [job(0, filename="Gear_v2_0.2mm_PLA_1h.gcode"),
                job(1, filename="Gear_v20_0.2mm_PLA_1h.gcode"),
                job(2, filename="folder/Gear+v2.gcode"),
                job(3, filename="Other_0.2mm_PLA_1h.gcode")]
        keys = pm.model_keys("", ["Gear_v2.stl"]) + pm.model_keys("", ["Gear v2.stl"])
        found = [j["filename"] for j in pm.same_model(jobs, keys)]
        self.assertEqual(found, ["Gear_v2_0.2mm_PLA_1h.gcode", "folder/Gear+v2.gcode"])

    def test_model_keys_from_project_and_objects(self):
        keys = pm.model_keys(r"C:\prints\Christmas set.3mf", ["Star.stl", "Star.stl", "x"])
        self.assertEqual(keys, ["christmas set", "star"])

    def test_settings_diff(self):
        then = {"layer_height": "0.2", "sparse_infill_density": "15%", "print_settings_id": "A",
                "curr_bed_type": "Textured PEI Plate", "textured_plate_temp": "55",
                "cool_plate_temp": "35", "enable_arc_fitting": "0", "only_in_old": "1",
                "machine_start_gcode": "PRINT_START", "filament_multitool_ramming": "0"}
        now = {"layer_height": "0.2", "sparse_infill_density": "20%", "print_settings_id": "B",
               "curr_bed_type": "Textured PEI Plate", "textured_plate_temp": "60",
               "cool_plate_temp": "40", "enable_arc_fitting": "disabled", "only_in_new": "1",
               "machine_start_gcode": "PRINT_START BED=60", "filament_multitool_ramming": "1"}
        rows = pm.settings_diff(then, now)
        keys = [r["key"] for r in rows]
        self.assertEqual(keys, ["sparse_infill_density", "textured_plate_temp",
                                "machine_start_gcode", "filament_multitool_ramming"])
        self.assertEqual(rows[0]["then"], "15%")
        self.assertEqual(rows[2]["now"], "(text changed)")
        self.assertEqual(pm.preset_changes(then, now)[0]["label"], "Process preset")


class SliceTest(unittest.TestCase):
    def slice_info(self, **changes):
        info = pm.parse_gcode(GCODE_HEAD, GCODE_TAIL)
        info["estimate"] = 3600
        info.update(changes)
        return info

    def test_forecast_uses_this_version_and_warm_up(self):
        jobs = [job(i, ratio=1.1, warm=300, version="2.5.0") for i in range(8)]
        out = pm.analyze_slice(self.slice_info(), history(*jobs), now=NOW)
        self.assertEqual(out["forecast"], pm.fmt_dur(3600 * 1.1 + 300))
        self.assertIn("10% longer than Orca said", out["basis"])
        self.assertIn("if you start now", out["finish"])

    def test_forecast_without_matching_version(self):
        jobs = [job(i, ratio=0.5, version="2.4.2") for i in range(8)]
        out = pm.analyze_slice(self.slice_info(), history(*jobs), now=NOW)
        self.assertEqual(out["forecast"], pm.fmt_dur(3600 + 300))
        self.assertIn("No finished prints sliced with OrcaSlicer 2.5", out["basis"])
        self.assertIn("OrcaSlicer 2.4 ran 50% shorter", out["basis"])

    def test_busy_printer_pushes_the_finish(self):
        data = history(*[job(i) for i in range(6)])
        data["status"] = {"print_stats": {"state": "printing", "print_duration": 600},
                          "virtual_sdcard": {"progress": 0.5}}
        out = pm.analyze_slice(self.slice_info(), data, now=NOW)
        self.assertIn("The printer is busy", out["finish"])

    def test_material_warning_and_model_history(self):
        jobs = ([job(i, material="PLA") for i in range(8)]
                + [job(20 + i, status="error", material="PLA") for i in range(8)]
                + [job(40, filename="Gear_v2_0.2mm_PLA_1h.gcode")])
        out = pm.analyze_slice(self.slice_info(), history(*jobs), now=NOW,
                               keys=["gear_v2"], earlier={"config": {"sparse_infill_density": "15%"},
                                                          "filename": "Gear_v2_0.2mm_PLA_1h.gcode",
                                                          "start_time": NOW - 86400})
        items = {i["title"]: i for i in out["items"]}
        self.assertEqual(items["PLA on this printer"]["level"], "warn")
        self.assertIn("1 print here, 1 finished", items["This model before"]["text"])
        self.assertEqual([r["key"] for r in out["diff"]["rows"]], ["sparse_infill_density"])

    def test_last_good_file_skips_missing_files(self):
        jobs = [job(0, filename="Gear_v2_a.gcode", exists=False),
                job(1, filename="Gear_v2_b.gcode", status="cancelled"),
                job(2, filename="Gear_v2_c.gcode")]
        self.assertEqual(pm.last_good_file(jobs, ["gear_v2"])["filename"], "Gear_v2_c.gcode")

    def test_fleet_row(self):
        data = history(*([job(i, material="PETG") for i in range(3)] + [job(9, material="PLA")]))
        row = pm.fleet_row("Big printer", data, {"material": "PETG"}, now=NOW)
        self.assertEqual(row["state"], "Idle")
        self.assertEqual(row["material"], "PETG: 100% of 3")
        self.assertEqual(row["rate"], "100% of 4 finished")


class AddressTest(unittest.TestCase):
    def test_round_trip(self):
        with tempfile.TemporaryDirectory() as folder:
            path = os.path.join(folder, "addresses.json")
            self.assertEqual(pm.load_addresses(path), {})
            pm.save_addresses({"Big printer": "100.64.0.12", "Mini": ""}, path)
            self.assertEqual(pm.load_addresses(path), {"Big printer": "100.64.0.12"})
            with open(path, "w", encoding="utf-8") as f:
                f.write("not json")
            self.assertEqual(pm.load_addresses(path), {})


